/**
 * @brief Get the atomic number from an element symbol
 *
 * @param element element symbol
 * @return unsigned int atomic number
 */
unsigned int PeriodicTable::get_atomic_number(const std::string& element) {
    if (element.empty()) {
        throw std::runtime_error("No element supplied to get_atomic_number.");
    }

    std::unordered_map<std::string, unsigned int>::const_iterator it =
        PeriodicTable::symbol_to_atomic_number.find(element);

    if (it == PeriodicTable::symbol_to_atomic_number.end()) {
        throw std::runtime_error("Invalid element encountered: " + element);
    }

    return it->second;
}

/**
 * @brief Get the element struct from an atomic number
 *
 * @param atomic_number atomic number
 * @return Element element struct
 */
Element PeriodicTable::get_element(const unsigned int atomic_number) {
    std::unordered_map<unsigned int, Element>::const_iterator it =
        PeriodicTable::atomic_number_to_element.find(atomic_number);

    if (it == PeriodicTable::atomic_number_to_element.end()) {
        throw std::runtime_error("Invalid atomic number encountered: " + atomic_number);
    }

    return it->second;
}
